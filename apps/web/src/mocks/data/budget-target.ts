// Helper function to build tree structure
export function buildAllocationTree<T extends { id: string; parentId: string | null; children?: T[] }>(
  items: T[],
  parentId: string | null = null
): T[] {
  return items
    .filter(item => item.parentId === parentId)
    .map(item => ({
      ...item,
      children: buildAllocationTree(items, item.id),
    }));
}

